import { mkdir, writeFile, cp, mkdtemp, lstat, access, rename, rm, readdir, copyFile, constants } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadContent, basePathSchema } from './content.js';
import { collections, labels, articleUrl, articlePage, homePage, layout, articleList } from './render.js';

const assets = fileURLToPath(new URL('../web/', import.meta.url));
async function copyPublic(source, destination) {
  let entries;
  try {
    if ((await lstat(source)).isSymbolicLink()) throw new Error(`Public asset symlinks are not allowed: ${source}`);
    entries = await readdir(source, { withFileTypes: true });
  } catch (error) { if (error.code === 'ENOENT') return; throw error; }
  await mkdir(destination, { recursive: true });
  for (const entry of entries) {
    if (entry.isSymbolicLink()) throw new Error(`Public asset symlinks are not allowed: ${entry.name}`);
    if (entry.isDirectory()) await copyPublic(path.join(source, entry.name), path.join(destination, entry.name));
    else await copyFile(path.join(source, entry.name), path.join(destination, entry.name), constants.COPYFILE_EXCL);
  }
}
export async function build(root, { basePath } = {}) {
  const content = await loadContent(root);
  if (basePath !== undefined) {
    const result = basePathSchema.safeParse(basePath);
    if (!result.success) throw new Error(`Invalid basePath: ${basePath}`);
    content.site.basePath = result.data;
  }
  const output = path.join(root, 'dist');
  const marker = '.fandomwiki-output';
  let exists = false;
  try {
    const info = await lstat(output);
    if (!info.isDirectory() || info.isSymbolicLink()) throw new Error('dist must be a real directory owned by FandomWiki');
    try { await access(path.join(output, marker)); } catch { throw new Error('Refusing to overwrite dist: missing FandomWiki output marker'); }
    exists = true;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const stage = await mkdtemp(path.join(root, '.wiki-build-'));
  const write = async (file, text) => {
    const destination = path.join(stage, file);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, text);
  };
  try {
    await cp(assets, path.join(stage, 'assets'), { recursive: true });
    // Public assets cannot overwrite generated HTML or generator scripts.
    await copyPublic(path.join(root, 'public/assets'), path.join(stage, 'assets'));
    await write('index.html', homePage(content));
    for (const [type, directory] of Object.entries(collections)) {
      await write(`${directory}/index.html`, layout(content, labels[type], `<p class="eyebrow">DANH MỤC</p><h1>${labels[type]}</h1>${articleList(content.entities.filter(e => e.type === type), content.site.basePath)}`, { active: type }));
    }
    for (const entity of content.entities) await write(`${collections[entity.type]}/${entity.id}.html`, articlePage(content, entity));
    await write('timeline.html', layout(content, 'Dòng thời gian', `<p class="eyebrow">BIÊN NIÊN SỬ</p><h1>Dòng thời gian</h1><p class="subtitle">Sự kiện được sắp xếp theo trường order trong YAML; thời điểm thuộc lịch của từng vũ trụ.</p>${articleList(content.entities.filter(e => e.type === 'event'), content.site.basePath)}`, { active: 'timeline' }));
    await write('search.html', layout(content, 'Tìm kiếm', '<p class="eyebrow">TRA CỨU</p><h1>Tìm kiếm thư viện</h1><p id="search-status" role="status">Nhập tên, tên khác hoặc từ khóa vào ô tìm kiếm.</p><label for="type-filter">Loại bài viết</label><select id="type-filter"><option value="">Tất cả</option><option value="universe">Vũ trụ</option><option value="series">Bộ truyện</option><option value="character">Nhân vật</option><option value="event">Sự kiện</option></select><div id="search-results" class="article-list"></div><noscript><p>Bật JavaScript để tìm kiếm, hoặc duyệt các danh mục trong thanh điều hướng.</p></noscript>'));
    await write('404.html', layout(content, 'Không tìm thấy trang', `<p class="eyebrow">404</p><h1>Trang này chưa có trong thư viện.</h1><p>Hãy tìm kiếm hoặc <a href="${content.site.basePath}/index.html">quay về trang chính</a>.</p>`));
    await write('search-index.json', JSON.stringify(content.entities.map(entity => ({ id: entity.id, name: entity.name, type: entity.type, summary: entity.summary, aliases: entity.aliases, tags: entity.tags, universe: entity.universe, url: articleUrl(entity, content.site.basePath) }))));
    await write('.nojekyll', '');
    await write(marker, 'Generated by fandomwiki-generator\n');
    // Retain the old build until all content has rendered successfully.
    const backup = `${stage}-previous`;
    if (exists) await rename(output, backup);
    try { await rename(stage, output); } catch (error) { if (exists) await rename(backup, output); throw error; }
    if (exists) await rm(backup, { recursive: true, force: true });
    return { output, articles: content.entities.length };
  } catch (error) {
    await rm(stage, { recursive: true, force: true });
    throw error;
  }
}
